#!/usr/bin/env node
// Build an idempotent SQL import for the app-owned D1 tables from a full
// Supabase export. Preserves published_edits.seq and proposals.id so cached
// client cursors remain valid.
//
// Usage: node scripts/import_d1.mjs [--source backups/supabase/2026-11-23]
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const ROOT = path.resolve(import.meta.dirname, '..');
const sourceArg = process.argv.indexOf('--source');
const outArg = process.argv.indexOf('--out');
const sourceDir = path.resolve(ROOT, sourceArg >= 0 ? process.argv[sourceArg + 1] : 'backups/supabase/2026-11-23');
const outDir = path.resolve(ROOT, outArg >= 0 ? process.argv[outArg + 1] : 'backups/d1/2026-11-23');
const outFile = path.join(outDir, 'import.sql');

function read(name) {
  const file = path.join(sourceDir, name);
  if (!fs.existsSync(file)) throw new Error(`Missing ${file}`);
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function quote(value) {
  if (value === null || value === undefined) return 'NULL';
  return "'" + String(value).replace(/'/g, "''") + "'";
}

function number(value) {
  const n = Number(value);
  return Number.isFinite(n) ? String(Math.trunc(n)) : '0';
}

function epoch(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return number(value);
  const parsed = Date.parse(value);
  return Number.isFinite(parsed) ? String(parsed) : 'NULL';
}

function canonical(value) {
  if (Array.isArray(value)) return '[' + value.map(canonical).join(',') + ']';
  if (value && typeof value === 'object') {
    return '{' + Object.keys(value).sort().map(key => JSON.stringify(key) + ':' + canonical(value[key])).join(',') + '}';
  }
  return JSON.stringify(value);
}

function hash(kind, payload) {
  return crypto.createHash('sha256').update(kind + '\n' + canonical(payload)).digest('hex');
}

const published = read('published_edits.json');
const proposals = read('proposals.json');
const state = read('publish_state.json');
const manifest = read('manifest.json');
const stateRow = state[0] || { version: 0, updated_at: Date.now() };

const lines = [
  '-- Generated by scripts/import_d1.mjs. Idempotent.',
  `-- Source: ${sourceDir}`,
  `-- Exported: ${manifest.exported_at}`,
  '',
];

for (const row of proposals) {
  const payload = JSON.stringify(row.payload);
  lines.push(
    'INSERT INTO proposals (id, kind, payload, payload_hash, summary, note, status, base_version, submitter_user_id, submitter_name, created_at, reviewed_at, reviewed_by) VALUES (' +
    [
      number(row.id),
      quote(row.kind),
      quote(payload),
      quote(hash(row.kind, row.payload)),
      quote(row.summary || ''),
      quote(row.note),
      quote(row.status || 'pending'),
      number(row.base_version),
      quote(row.submitter),
      quote(row.submitter_name),
      epoch(row.created_at),
      epoch(row.reviewed_at),
      quote(row.reviewed_by),
    ].join(', ') +
    ') ON CONFLICT(id) DO UPDATE SET payload=excluded.payload, payload_hash=excluded.payload_hash, summary=excluded.summary, note=excluded.note, status=excluded.status, base_version=excluded.base_version, submitter_user_id=excluded.submitter_user_id, submitter_name=excluded.submitter_name, created_at=excluded.created_at, reviewed_at=excluded.reviewed_at, reviewed_by=excluded.reviewed_by;',
  );
}

for (const row of published) {
  lines.push(
    'INSERT INTO published_edits (seq, kind, payload, proposal_id, published_at) VALUES (' +
    [
      number(row.seq),
      quote(row.kind),
      quote(JSON.stringify(row.payload)),
      row.proposal_id === null || row.proposal_id === undefined ? 'NULL' : number(row.proposal_id),
      epoch(row.published_at),
    ].join(', ') +
    ') ON CONFLICT(seq) DO UPDATE SET kind=excluded.kind, payload=excluded.payload, proposal_id=excluded.proposal_id, published_at=excluded.published_at;',
  );
}

const maxSeq = published.reduce((max, row) => Math.max(max, Number(row.seq) || 0), 0);
const maxProposal = proposals.reduce((max, row) => Math.max(max, Number(row.id) || 0), 0);
lines.push(
  `INSERT INTO publish_state (id, version, updated_at) VALUES (1, ${number(stateRow.version)}, ${epoch(stateRow.updated_at)}) ON CONFLICT(id) DO UPDATE SET version=MAX(version, excluded.version), updated_at=excluded.updated_at;`,
  `UPDATE sqlite_sequence SET seq=MAX(seq, ${maxSeq}) WHERE name='published_edits';`,
  `UPDATE sqlite_sequence SET seq=MAX(seq, ${maxProposal}) WHERE name='proposals';`,
  '',
);

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, lines.join('\n'), { mode: 0o600 });

const importManifest = {
  generated_at: new Date().toISOString(),
  source: sourceDir,
  published_edits: published.length,
  proposals: proposals.length,
  max_published_seq: maxSeq,
  max_proposal_id: maxProposal,
  version: Number(stateRow.version) || 0,
};
fs.writeFileSync(path.join(outDir, 'manifest.json'), JSON.stringify(importManifest, null, 2) + '\n', { mode: 0o600 });

console.log(`Wrote ${outFile}`);
console.log(`published_edits=${published.length} proposals=${proposals.length} version=${importManifest.version} max_seq=${maxSeq}`);
