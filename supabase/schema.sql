-- Khristian Labu — approved-change sync
--
-- Run this once in the Supabase SQL editor (Dashboard → SQL → New query → Run).
-- It is idempotent: re-running it is safe.
--
-- Model
--   proposals      every device's submitted change, waiting for review
--   published_edits  the canonical overlay of approved changes (append-only)
--   publish_state    one row; its `version` bumps on every publish
--   admins           auth.users allowed to review + publish
--
-- The app keeps songs.json as the immutable base corpus and replays
-- published_edits (then the device's own edits) over it. Publishing therefore
-- needs no rebuild, no redeploy and no git commit — devices pick it up on their
-- next launch/focus check.
-- ─────────────────────────────────────────────────────────────────────────────

create table if not exists public.admins (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  email      text,
  created_at timestamptz not null default now()
);

create table if not exists public.publish_state (
  id         int primary key default 1 check (id = 1),
  version    bigint not null default 0,
  updated_at timestamptz not null default now()
);

insert into public.publish_state (id, version)
values (1, 0)
on conflict (id) do nothing;

create table if not exists public.published_edits (
  seq          bigint generated by default as identity primary key,
  kind         text not null check (kind in ('song', 'struct', 'chord')),
  payload      jsonb not null,
  proposal_id  bigint unique,
  published_at timestamptz not null default now()
);

create table if not exists public.proposals (
  id             bigint generated by default as identity primary key,
  kind           text not null check (kind in ('song', 'struct', 'chord')),
  payload        jsonb not null,
  summary        text not null default '',
  note           text,
  status         text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  base_version   bigint not null default 0,
  submitter      uuid default auth.uid(),
  submitter_name text,
  created_at     timestamptz not null default now(),
  reviewed_at    timestamptz,
  reviewed_by    uuid,
  constraint proposals_payload_size check (octet_length(payload::text) < 200000)
);

create index if not exists proposals_pending_idx
  on public.proposals (created_at asc) where status = 'pending';

-- ─── helpers ────────────────────────────────────────────────────────────────

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

create or replace function public.am_i_admin()
returns boolean
language sql
stable
as $$
  select public.is_admin();
$$;

-- ─── writes ─────────────────────────────────────────────────────────────────

-- A signed-in admin's own edit goes live immediately.
create or replace function public.publish_edit(p_kind text, p_payload jsonb)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v bigint;
begin
  if not public.is_admin() then
    raise exception 'not an admin' using errcode = '42501';
  end if;
  if p_kind not in ('song', 'struct', 'chord') then
    raise exception 'unknown kind %', p_kind;
  end if;
  if octet_length(p_payload::text) > 200000 then
    raise exception 'payload too large';
  end if;

  insert into public.published_edits (kind, payload) values (p_kind, p_payload);
  update public.publish_state
     set version = version + 1, updated_at = now()
   where id = 1
  returning version into v;
  return v;
end;
$$;

-- Anyone (including an anonymous device) can submit a change for review.
-- Identical pending payloads are de-duplicated, and a global pending cap keeps
-- the queue from being flooded.
create or replace function public.submit_proposal(
  p_kind text,
  p_payload jsonb,
  p_summary text,
  p_name text default null,
  p_base_version bigint default 0
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  existing bigint;
  pending_count bigint;
  new_id bigint;
begin
  if p_kind not in ('song', 'struct', 'chord') then
    raise exception 'unknown kind %', p_kind;
  end if;
  if octet_length(p_payload::text) > 200000 then
    raise exception 'payload too large';
  end if;

  select id into existing
    from public.proposals
   where status = 'pending'
     and kind = p_kind
     and payload = p_payload
   limit 1;
  if existing is not null then
    return existing;
  end if;

  select count(*) into pending_count from public.proposals where status = 'pending';
  if pending_count >= 1000 then
    raise exception 'review queue is full' using errcode = '54000';
  end if;

  insert into public.proposals (kind, payload, summary, submitter_name, base_version)
  values (p_kind, p_payload, left(coalesce(p_summary, ''), 300), left(coalesce(p_name, ''), 120), p_base_version)
  returning id into new_id;
  return new_id;
end;
$$;

-- Approve one or more proposals atomically-ish: each becomes a published edit
-- and the publish version advances once per batch.
create or replace function public.approve_proposals(p_ids bigint[])
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  p public.proposals;
  v bigint;
  n int := 0;
begin
  if not public.is_admin() then
    raise exception 'not an admin' using errcode = '42501';
  end if;

  for p in
    select * from public.proposals
     where id = any(p_ids) and status = 'pending'
     order by id
     for update
  loop
    insert into public.published_edits (kind, payload, proposal_id)
    values (p.kind, p.payload, p.id);

    update public.proposals
       set status = 'approved', reviewed_at = now(), reviewed_by = auth.uid()
     where id = p.id;
    n := n + 1;
  end loop;

  if n = 0 then
    return null;
  end if;

  update public.publish_state
     set version = version + 1, updated_at = now()
   where id = 1
  returning version into v;
  return v;
end;
$$;

create or replace function public.reject_proposals(p_ids bigint[], p_note text default null)
returns int
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'not an admin' using errcode = '42501';
  end if;
  update public.proposals
     set status = 'rejected', note = left(coalesce(p_note, ''), 300),
         reviewed_at = now(), reviewed_by = auth.uid()
   where id = any(p_ids) and status = 'pending';
  return (select count(*)::int from public.proposals where id = any(p_ids) and status = 'rejected');
end;
$$;

-- ─── row level security ─────────────────────────────────────────────────────

alter table public.admins          enable row level security;
alter table public.publish_state   enable row level security;
alter table public.published_edits enable row level security;
alter table public.proposals       enable row level security;

drop policy if exists "admins read own row" on public.admins;
create policy "admins read own row" on public.admins
  for select to authenticated
  using (user_id = auth.uid());

drop policy if exists "publish state is public" on public.publish_state;
create policy "publish state is public" on public.publish_state
  for select to anon, authenticated
  using (true);

drop policy if exists "published edits are public" on public.published_edits;
create policy "published edits are public" on public.published_edits
  for select to anon, authenticated
  using (true);

drop policy if exists "admins see every proposal" on public.proposals;
create policy "admins see every proposal" on public.proposals
  for select to authenticated
  using (public.is_admin() or submitter = auth.uid());

-- All writes go through the security-definer functions above.
revoke insert, update, delete on public.proposals from anon, authenticated;
revoke insert, update, delete on public.published_edits from anon, authenticated;
revoke insert, update, delete on public.publish_state from anon, authenticated;
revoke insert, update, delete on public.admins from anon, authenticated;

grant select on public.publish_state, public.published_edits to anon, authenticated;
grant select on public.proposals to authenticated;
grant execute on function public.is_admin() to anon, authenticated;
grant execute on function public.am_i_admin() to anon, authenticated;
grant execute on function public.publish_edit(text, jsonb) to authenticated;
grant execute on function public.submit_proposal(text, jsonb, text, text, bigint) to anon, authenticated;
grant execute on function public.approve_proposals(bigint[]) to authenticated;
grant execute on function public.reject_proposals(bigint[], text) to authenticated;

